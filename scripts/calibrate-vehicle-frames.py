"""Compile alpha bounds once, outside the game loop. Input is the published artwork."""
import argparse,json
from pathlib import Path
from PIL import Image
parser=argparse.ArgumentParser();parser.add_argument('source',type=Path);args=parser.parse_args()
frames={}
for model in ['truck','buggy','hover']:
 frames[model]={}
 for direction in ['east','southeast','south','southwest','west','northwest','north','northeast']:
  im=Image.open(args.source/f'vehicle-{model}-{direction}.png').convert('RGBA')
  bounds=im.getchannel('A').point(lambda a:255 if a>230 else 0).getbbox()
  if not bounds:raise ValueError('Empty vehicle')
  x,y,right,bottom=bounds
  # Retain three pixels of edge antialiasing, excluding stray near-transparent pixels.
  x=max(0,x-3);y=max(0,y-3);right=min(im.width,right+3);bottom=min(im.height,bottom+3)
  frames[model][direction]=dict(x=x,y=y,w=right-x,h=bottom-y,fullWidth=im.width,fullHeight=im.height)
Path('js/vehicle-artwork.js').write_text("// Generated by scripts/calibrate-vehicle-frames.py; do not scan pixels during rendering.\nexport const VEHICLE_ARTWORK="+json.dumps(frames,separators=(',',':'))+";\n"+'''const directions=['east','southeast','south','southwest','west','northwest','north','northeast'];
const nominal=facing=>['north','south'].includes(facing)?100:['east','west'].includes(facing)?160:145;
function envelope(model,facing){
 const frames=VEHICLE_ARTWORK[model],front=frames.south,side=frames.east;
 const angle=directions.indexOf(facing)*Math.PI/4,vertical=Math.abs(Math.sin(angle)),horizontal=Math.abs(Math.cos(angle));
 // Project one body into each view. Independent source canvases cannot define its scale.
 return {width:front.w/front.fullWidth*100*vertical+side.w/side.fullWidth*160*horizontal,
 height:front.h/front.fullWidth*100*(.85+.15*vertical)};
}
export function vehicleFrame(model,facing,authoredFacing='south'){
 const source=VEHICLE_ARTWORK[model]?.[facing],authored=VEHICLE_ARTWORK[model]?.[authoredFacing];
 if(!source||!authored)return null;
 const target=envelope(model,facing),baseline=envelope(model,authoredFacing);
 // The visible width of the originally placed frame matches the width saved in the editor.
 const calibration=nominal(authoredFacing)*authored.w/authored.fullWidth/baseline.width;
 return {...source,width:target.width*calibration,height:target.height*calibration};
}
''')
