"""Compile sheet cells once. Render with one uniform pixel scale, never stretch views."""
import argparse,json
from pathlib import Path
from PIL import Image
import numpy as np
from scipy import ndimage
parser=argparse.ArgumentParser();parser.add_argument('source',type=Path);args=parser.parse_args()
reference=json.loads(Path('scripts/vehicle-placement-reference.json').read_text())
frames={};directions=['north','northeast','east','southeast','south','southwest','west','northwest']
for model in ['truck','buggy','hover']:
 im=Image.open(args.source/f'vehicle-{model}-sheet-v5.png').convert('RGBA')
 alpha=np.array(im.getchannel('A'))>230
 labels,count=ndimage.label(ndimage.binary_dilation(alpha,iterations=2))
 slices=ndimage.find_objects(labels);areas=np.bincount(labels.ravel())
 largest=np.argsort(areas[1:])[-8:]+1
 if len(largest)!=8 or min(areas[largest])<max(areas[largest])*.5:raise ValueError('Incomplete turntable')
 boxes=[]
 for label in largest:
  rows,cols=slices[label-1];boxes.append((cols.start,rows.start,cols.stop,rows.stop))
 # The generated atlas has transparent gutters, but its physical pixel size need not divide by four.
 # Read each isolated vehicle as a source rectangle; never cut at an assumed grid line.
 boxes.sort(key=lambda b:(b[1]+b[3])/2)
 ordered=sorted(boxes[:4],key=lambda b:(b[0]+b[2])/2)+sorted(boxes[4:],key=lambda b:(b[0]+b[2])/2)
 frames[model]={}
 for direction,(x,y,right,bottom) in zip(directions,ordered):
  w,h=right-x,bottom-y
  if x<1 or y<1 or right>=im.width or bottom>=im.height:raise ValueError('Clipped vehicle')
  frames[model][direction]=dict(x=int(x),y=int(y),w=int(w),h=int(h),fullWidth=im.width,fullHeight=im.height,visibleWidth=int(w),visibleHeight=int(h))
Path('js/vehicle-artwork.js').write_text('// Generated by scripts/calibrate-vehicle-frames.py; all cells share the same camera and pixel scale.\nexport const VEHICLE_ARTWORK='+json.dumps(frames,separators=(',',':'))+';\nexport const VEHICLE_PLACEMENT_REFERENCE='+json.dumps(reference,separators=(',',':'))+';\n'+'''const nominal=facing=>['north','south'].includes(facing)?100:['east','west'].includes(facing)?160:145;
export function vehicleFrame(model,facing,authoredFacing='south'){
 const source=VEHICLE_ARTWORK[model]?.[facing],authored=VEHICLE_ARTWORK[model]?.[authoredFacing],original=VEHICLE_PLACEMENT_REFERENCE[model]?.[authoredFacing];
 if(!source||!authored||!original)return null;
 // Match the placed frame's visible editor width, then use ONE pixel scale for the whole turntable.
 const pixelScale=nominal(authoredFacing)*original.w/original.fullWidth/authored.visibleWidth;
 return {...source,width:source.w*pixelScale,height:source.h*pixelScale,anchorX:source.w*.5*pixelScale,anchorY:source.h*.6*pixelScale};
}
''')
